#!/usr/bin/env Rscript
# Audit of the released (legacy) version of a package: the starting point of a modernisation (phase P0).
# Usage: Rscript tools/audit-legacy.R <old.tar.gz | old_source_dir> [--out=dev]
# Writes <out>/AUDIT.md (exports and their arguments, return components, documentation gaps, data sets, code
# patterns to replace, with file:line) and <out>/legacy/examples/<topic>.R (the example code of every help page, run
# later by tools/legacy-snapshot.R). Read AUDIT.md, then fill its "Findings" section by hand: wrong formulas,
# arguments that are ignored, results that disagree with the published examples.
args <- commandArgs(trailingOnly = TRUE)
out <- sub("^--out=", "", grep("^--out=", args, value = TRUE)[1L])
if (is.na(out)) out <- "dev"
src <- args[!startsWith(args, "--")][1L]
if (is.na(src)) stop("usage: audit-legacy.R <old.tar.gz | old_source_dir> [--out=dev]")
if (grepl("\\.tar\\.gz$", src)) {
  tmp <- tempfile("legacy")
  dir.create(tmp)
  utils::untar(src, exdir = tmp)
  src <- list.dirs(tmp, recursive = FALSE)[1L]
}
dcf <- read.dcf(file.path(src, "DESCRIPTION"))
pkg <- dcf[1L, "Package"]
ver <- dcf[1L, "Version"]
dir.create(file.path(out, "legacy", "examples"), recursive = TRUE, showWarnings = FALSE)
md <- c(sprintf("# Audit of %s %s", pkg, ver), "",
        "Generated by tools/audit-legacy.R; the section Findings is written by hand.", "")

# exports and arguments (parsed, not loaded)
ns <- if (file.exists(file.path(src, "NAMESPACE"))) readLines(file.path(src, "NAMESPACE"), warn = FALSE) else character()
exports <- sub("^export\\((.*)\\)$", "\\1", grep("^export\\(", ns, value = TRUE))
rfiles <- list.files(file.path(src, "R"), pattern = "\\.[Rr]$", full.names = TRUE)
defs <- list()
for (f in rfiles) {
  ex <- tryCatch(parse(f, keep.source = FALSE), error = function(e) NULL)
  for (e in ex) {
    if (is.call(e) && as.character(e[[1L]]) %in% c("<-", "=") && is.call(e[[3L]]) &&
        identical(e[[3L]][[1L]], as.name("function"))) {
      nm <- as.character(e[[2L]])
      defs[[nm]] <- list(file = basename(f), formals = names(e[[3L]][[2L]]), body = e[[3L]][[3L]])
    }
  }
}
# names of every list(name = value, ...) built in a function body: the components it can return
list_names <- function(e) {
  if (!is.call(e)) return(character())
  here <- if (identical(e[[1L]], as.name("list")) && length(e) > 2L && !is.null(names(e)) &&
              all(nzchar(names(e)[-1L]))) names(e)[-1L] else character()
  c(here, unlist(lapply(as.list(e)[-1L], list_names)))
}
md <- c(md, "## Exported functions", "", "| function | arguments | file | components returned (list names) |",
        "|---|---|---|---|")
for (nm in exports) {
  d <- defs[[nm]]
  comps <- if (is.null(d)) "" else paste(unique(list_names(d$body)), collapse = ", ")
  md <- c(md, sprintf("| `%s` | %s | %s | %s |", nm, if (is.null(d)) "?" else paste(d$formals, collapse = ", "),
                      if (is.null(d)) "?" else d$file, comps))
}
md <- c(md, "", "The last column lists the names of every `list(name = value, ...)` built in the body.", "")

# help pages: sections present, examples extracted
rd <- list.files(file.path(src, "man"), pattern = "\\.Rd$", full.names = TRUE)
md <- c(md, "## Help pages", "", "| topic | value | details | references | examples | maths |", "|---|---|---|---|---|---|")
for (f in rd) {
  x <- readLines(f, warn = FALSE)
  has <- function(tag) if (any(grepl(paste0("^\\\\", tag, "\\{"), x))) "yes" else "**no**"
  topic <- sub("\\.Rd$", "", basename(f))
  md <- c(md, sprintf("| %s | %s | %s | %s | %s | %s |", topic, has("value"), has("details"), has("references"),
                      has("examples"), if (any(grepl("\\\\(d)?eqn\\{", x))) "yes" else "none"))
  rd_obj <- tryCatch(tools::parse_Rd(f), error = function(e) NULL)
  if (!is.null(rd_obj)) {
    exf <- file.path(out, "legacy", "examples", paste0(topic, ".R"))
    tools::Rd2ex(rd_obj, out = exf, commentDontrun = TRUE, commentDonttest = FALSE)
  }
}
md <- c(md, "")

# data sets
dfiles <- list.files(file.path(src, "data"), full.names = TRUE)
if (length(dfiles)) {
  md <- c(md, "## Data sets", "", "| file | objects (class, rows x columns, columns) |", "|---|---|")
  for (f in dfiles) {
    e <- new.env()
    nms <- tryCatch(if (grepl("\\.(RData|rda)$", f)) load(f, envir = e) else character(), error = function(err) character())
    info <- vapply(nms, function(n) {
      o <- e[[n]]
      sprintf("`%s` (%s, %s; %s)", n, class(o)[1L], paste(dim(o), collapse = " x "),
              paste(utils::head(names(o), 8L), collapse = ", "))
    }, "")
    md <- c(md, sprintf("| %s | %s |", basename(f), paste(info, collapse = "; ")))
  }
  md <- c(md, "")
}

# code patterns to replace (file:line)
pat <- list(
    "`T` / `F` for TRUE / FALSE"                    = "(=|,|\\()\\s*[TF]\\s*(\\)|,|$)"
  , "`deparse(substitute())` column capture"        = "deparse\\(substitute\\("
  , "fixed column names inside functions"           = "\\[\\[\"[A-Za-z][A-Za-z0-9._]*\"\\]\\]"
  , "`sapply()` (use `vapply()`)"                   = "\\bsapply\\("
  , "`1:n` loops (use `seq_len()` / `seq_along()`)" = "\\bfor\\s*\\([^)]*\\bin\\s+1:"
  , "nested `for` loops (vectorise or C++)"         = "^\\s*for\\s*\\("
  , "`aov()` / `lm()` refitted per call"            = "\\b(aov|lm)\\("
  , "`tapply()` (use collapse / data.table)"        = "\\btapply\\("
  , "`library()` / `require()` in package code"     = "\\b(library|require)\\("
  , "`print()` / `cat()` inside computations"       = "^\\s*(print|cat)\\("
  , "`<<-` (global assignment)"                     = "<<-"
  , "`attach()`"                                    = "\\battach\\("
  , "`class(x) <- ` on results without a class"     = "class\\([A-Za-z.]+\\)\\s*<-"
  )
md <- c(md, "## Code patterns", "", "| pattern | count | where (first 8) |", "|---|---|---|")
for (p in names(pat)) {
  hits <- character()
  for (f in rfiles) {
    x <- readLines(f, warn = FALSE)
    code <- !grepl("^\\s*#", x)
    k <- which(code & grepl(pat[[p]], x, perl = TRUE))
    if (length(k)) hits <- c(hits, sprintf("%s:%d", basename(f), k))
  }
  md <- c(md, sprintf("| %s | %d | %s |", p, length(hits), paste(utils::head(hits, 8L), collapse = ", ")))
}
# repeated blocks: identical non-trivial lines that occur many times
all_lines <- unlist(lapply(rfiles, function(f) trimws(readLines(f, warn = FALSE))))
all_lines <- all_lines[nchar(all_lines) > 40L & !startsWith(all_lines, "#")]
tab <- sort(table(all_lines), decreasing = TRUE)
rep_lines <- tab[tab >= 3L]
md <- c(md, "", sprintf("Repeated code: %d distinct lines occur 3 or more times (copied branches; merge them into one core).",
                        length(rep_lines)), "")
if (length(rep_lines)) md <- c(md, "```", sprintf("%3d x %s", as.integer(utils::head(rep_lines, 10L)),
                                                  substr(names(utils::head(rep_lines, 10L)), 1L, 100L)), "```", "")
md <- c(md, "## Dependencies", "", sprintf("* %s: %s", c("Depends", "Imports", "Suggests"),
                                          vapply(c("Depends", "Imports", "Suggests"), function(f)
                                            if (f %in% colnames(dcf)) gsub("\\s+", " ", dcf[1L, f]) else "", "")), "",
        "## Findings (by hand)", "", "* ...", "")
writeLines(md, file.path(out, "AUDIT.md"))
cat(sprintf("%s %s: %d exports, %d help pages, %d data files -> %s\n", pkg, ver, length(exports), length(rd),
            length(dfiles), file.path(out, "AUDIT.md")))
